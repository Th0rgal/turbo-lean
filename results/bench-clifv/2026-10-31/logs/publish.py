#!/usr/bin/env python3
"""Copy measured benchmark artifacts into the publication worktree and render README.md.

Only numbers read from the runner's results.json / GNU time files are printed.
"""
import json, re, shutil, statistics, subprocess, sys, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "bench" / "results"
PUB = ROOT / "pub"
DATE = "2026-10-31"
DEST = PUB / "results" / "bench-clifv" / DATE
SCHEMA = ROOT / "repo" / "scripts" / "bench_clifv.schema.json"
note = sys.argv[1] if len(sys.argv) > 1 else ""

DEST.mkdir(parents=True, exist_ok=True)
if (RES / "logs").exists():
    shutil.copytree(RES / "logs", DEST / "logs", dirs_exist_ok=True)
for extra in ("runner.log", "start.txt", "exit.txt"):
    if (ROOT / "bench" / extra).exists():
        shutil.copy2(ROOT / "bench" / extra, DEST / "logs" / extra) if (DEST / "logs").exists() else None
shutil.copy2(ROOT / "meta" / "load.log", DEST / "load.log")
if (ROOT / "meta" / "cargo_build.log").exists():
    (DEST / "logs").mkdir(exist_ok=True)
    shutil.copy2(ROOT / "meta" / "cargo_build.log", DEST / "logs" / "turbo-lean-cargo-build.log")
    shutil.copy2(ROOT / "meta" / "run.sh", DEST / "logs" / "run.sh")

report = None
schema_status = "no results.json yet (the runner writes it only after the first complete pair)"
if (RES / "results.json").exists():
    report = json.loads((RES / "results.json").read_text())
    import jsonschema
    try:
        jsonschema.validate(report, json.loads(SCHEMA.read_text()))
        schema_status = "VALID against scripts/bench_clifv.schema.json (jsonschema)"
    except jsonschema.ValidationError as e:
        schema_status = f"SCHEMA INVALID: {e.message}"
    shutil.copy2(RES / "results.json", DEST / "report.json")
    if (RES / "results.md").exists():
        shutil.copy2(RES / "results.md", DEST / "runner-results.md")

facts = json.loads((ROOT / "meta" / "facts.json").read_text())

def parse_time(path):
    txt = path.read_text(errors="replace")
    m = re.search(r"Elapsed \(wall clock\) time.*: (?:(\d+):)?(\d+):([\d.]+)", txt)
    if not m:
        return None
    h, mi, s = m.groups()
    return (int(h or 0) * 3600 + int(mi) * 60 + float(s))

def fmt(x):
    return "n/a" if x is None else f"{x:.2f}"

lines = [f"# clifv paired benchmark (A0e) — uruk, {DATE}", ""]
lines += ["**Status:** " + (report["status"] if report else "running (no complete pair yet)") +
          (f" — {note}" if note else ""), ""]
lines += ["Only measured values are reported. Generated by `meta/publish.py` from the runner's",
          "`results.json` (copied verbatim as `report.json`) and GNU time files under `logs/`.", "",
          f"report.json schema check: {schema_status}", ""]

lines += ["## Wall time per scenario per arm (seconds)", "",
          "| Scenario | Arm | #pairs | median | min | max | exit codes | parity per pair | verdict |",
          "|---|---|---|---|---|---|---|---|---|"]
if report:
    for sc in report["scenarios"]:
        invalid = any(p["parity"] == "INVALID" for p in sc["pairs"])
        reasons = sc["summary"]["ratio_suppressed_reasons"]
        for arm in ("stock", "turbo"):
            walls = [p[arm]["wall_s"] for p in sc["pairs"]]
            codes = ",".join(str(p[arm]["exit_code"]) for p in sc["pairs"])
            par = ",".join(p["parity"] for p in sc["pairs"])
            verdict = "INVALID" if invalid else ("FAIL" if any(p["parity"] == "FAIL" for p in sc["pairs"]) else "valid")
            lines.append(f"| {sc['name']} | {'A stock `lake build FV`' if arm=='stock' else 'B `turbo-lean --no-daemon build FV`'} "
                         f"| {len(walls)} | {fmt(statistics.median(walls))} | {fmt(min(walls))} | {fmt(max(walls))} "
                         f"| {codes} | {par} | {verdict} |")
else:
    lines.append("| (none yet) | | 0 | | | | | | |")
lines.append("")

if report:
    lines += ["## Runner ratio gate", ""]
    for sc in report["scenarios"]:
        s = sc["summary"]
        if s["speedup_claim_allowed"]:
            r = s["paired_wall_ratio"]
            lines.append(f"- **{sc['name']}**: paired wall ratio A/B mean {r['mean']:.3f}, median {r['median']:.3f}, "
                         f"CV {r['cv']:.3f}, bootstrap 95% CI [{r['bootstrap_95_ci'][0]:.3f}, {r['bootstrap_95_ci'][1]:.3f}]")
        else:
            lines.append(f"- **{sc['name']}**: ratio SUPPRESSED by runner — " + "; ".join(s["ratio_suppressed_reasons"]))
    lines.append("")
    lines += ["## Per-run measurements", "",
              "| Scenario | Pair | Arm | wall s | CPU s | peak RSS KiB | exit | load before (1/5/15) | load after (1/5/15) |",
              "|---|---|---|---|---|---|---|---|---|"]
    for sc in report["scenarios"]:
        for p in sc["pairs"]:
            for arm in ("stock", "turbo"):
                m = p[arm]
                lb = "/".join(f"{x:.2f}" for x in m["load_before"]); la = "/".join(f"{x:.2f}" for x in m["load_after"])
                lines.append(f"| {sc['name']} | {p['index']} | {arm} | {m['wall_s']:.2f} | {m['cpu_s']:.2f} | {m['peak_rss_kib']} "
                             f"| {m['exit_code']} | {lb} | {la} |")
    lines.append("")

# untimed primes (measured by GNU time, outside the experiment's timers)
primes = sorted((RES / "logs").glob("prime-*.time")) if (RES / "logs").exists() else []
if primes:
    lines += ["## Untimed primes (GNU time; not part of the paired comparison)", "", "| prime | wall s |", "|---|---|"]
    for p in primes:
        lines.append(f"| {p.stem} | {fmt(parse_time(p))} |")
    lines.append("")

m = report["machine"] if report else {}
lines += ["## Provenance", "",
          f"- Host: `{facts['hostname']}` — {facts['cpu']}; nproc={facts['nproc']}; RAM {facts['mem']}; "
          f"swap {facts['swap']}; kernel `{facts['kernel']}`",
          f"- Disk (work dir): {facts['disk']} (device id {facts['work_dev']}; /dev/shm device id {facts['shm_dev']})",
          f"- clifv SHA: `{m.get('clifv_sha', facts['clifv_sha'])}` (doc default `5018b95`)",
          f"- turbo-lean SHA (origin/main at start): `{m.get('turbo_lean_sha', facts['turbo_sha'])}`",
          f"- turbo-lean binary sha256: `{m.get('turbo_binary_sha256', 'pending')}`; version `{m.get('turbo_version', 'pending')}`",
          f"- Lean: `{m.get('lean_version', 'pending')}`; toolchain `{m.get('toolchain', facts['toolchain'])}`",
          f"- LEAN_NUM_THREADS: `{m.get('LEAN_NUM_THREADS', None)}` (unset ⇒ null)",
          f"- Command: `scripts/bench_clifv.sh --scenarios cold,warm --pairs 2 --sha 5018b95` (+ explicit `--turbo`, "
          "`--turbo-repo`, `--lake $ELAN_HOME/bin/lake`, work/output dirs on /dev/md2); see `logs/run.sh`",
          "- Benchmark shell: `TURBO_LEAN_TELEMETRY=off`; `TURBO_LEAN_COMPUTE_NODES`, `LEAN_NATIVE_COLAB_API_URL`, "
          "`LEAN_NATIVE_COLAB_TOKEN` were **unset** (this node's mission env sets them; leaving them would let arm B "
          "contact remote compute nodes). `SANDBOXED_ALLOW_RAW_LAKE=1` only silences the node's lake-wrapper warning; "
          "arm A invoked the real elan `lake` directly.",
          f"- Runner start (UTC): {facts.get('bench_start', 'n/a')}; machine load at runner start "
          f"{m.get('load_before', 'n/a')}, at last checkpoint {m.get('load_after', 'n/a')}", ""]

# load summary from load.log
loads = re.findall(r"=== (\S+) \[(\S+)\]\n.*load average: ([\d.]+), ([\d.]+), ([\d.]+)", (DEST / "load.log").read_text())
lines += ["## Host load (shared node — load is part of the result)", "",
          f"`load.log` holds `uptime`, memory and top-10 CPU consumers {len(loads)} times (before, every 30 min, after).", "",
          "| UTC | label | load 1/5/15 |", "|---|---|---|"]
for ts, lab, a, b, c in loads:
    lines.append(f"| {ts} | {lab} | {a} / {b} / {c} |")
if loads:
    one = [float(x[2]) for x in loads]
    lines += ["", f"1-min load across snapshots: min {min(one):.2f}, median {statistics.median(one):.2f}, max {max(one):.2f} "
              f"on an {facts['nproc']}-thread host. Other tenants' Lean builds, rustc and agent processes were running "
              "throughout (see load.log); the host was **not idle** as BENCH_CLIFV.md requires."]
lines.append("")
lines += ["## Interpretation", "", (facts.get("interpretation") or
          "Pending completion. No speedup claim is made in this file unless the runner's ratio gate allows one."), ""]
(DEST / "README.md").write_text("\n".join(lines))
print("\n".join(lines))
