//! P0-1: `check --decl` must never verify (or cache) a target that uses `sorry`, while prefix
//! `sorry` stubs keep working. Drives the real CLI, through the warm local daemon and without it.
use serde_json::Value;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::time::{SystemTime, UNIX_EPOCH};

struct Project(PathBuf);
impl Project {
    fn new(daemon: bool) -> Self {
        let root = std::env::temp_dir().join(format!(
            "turbo_check_decl_sorry_{}_{}_{}",
            daemon,
            std::process::id(),
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::create_dir_all(&root).unwrap();
        fs::write(
            root.join("lean-toolchain"),
            include_str!("../../../lean/lean-toolchain"),
        )
        .unwrap();
        // The exact P0-1 reproducer.
        fs::write(
            root.join("F.lean"),
            "theorem good : 1 + 1 = 2 := rfl\ntheorem bad : False := sorry\n",
        )
        .unwrap();
        // `uses_good` relies on the prefix stub of `good`; `sneaky` hides its `sorry` behind a macro
        // (no `sorry` token in the target), and a comment mentions `:= sorry`.
        fs::write(
            root.join("G.lean"),
            "theorem good : 1 + 1 = 2 := rfl\n\
             theorem uses_good : 1 + 1 = 2 := good\n\
             macro \"cheat\" : term => `(sorry)\n\
             -- theorem t : True := sorry\n\
             theorem sneaky : False := cheat\n",
        )
        .unwrap();
        // A `sorry` no lexical scan sees: the macro builds the `sorry` syntax node from strings.
        fs::write(
            root.join("H.lean"),
            "theorem good : 1 + 1 = 2 := rfl\n\
             macro \"cheat\" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 \"Lean\" \"Parser\" \"Term\" (\"sor\" ++ \"ry\")) #[Lean.Syntax.atom .none (\"sor\" ++ \"ry\")]⟩\n\
             theorem sneaky : False := cheat\n",
        )
        .unwrap();
        // Non-shardable files: the hidden-sorry theorem before a valid one, and one generated by a
        // command macro (no theorem in the text at all).
        fs::write(
            root.join("L.lean"),
            "macro \"cheat\" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 \"Lean\" \"Parser\" \"Term\" (\"sor\" ++ \"ry\")) #[Lean.Syntax.atom .none (\"sor\" ++ \"ry\")]⟩\n\
             #guard_msgs (drop warning) in\n\
             theorem bad : False := cheat\n\
             theorem good : True := trivial\n",
        )
        .unwrap();
        fs::write(
            root.join("M.lean"),
            "macro \"cheat\" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 \"Lean\" \"Parser\" \"Term\" (\"sor\" ++ \"ry\")) #[Lean.Syntax.atom .none (\"sor\" ++ \"ry\")]⟩\n\
             macro \"makeBad\" : command => `(theorem bad : False := cheat)\n\
             #guard_msgs (drop warning) in\n\
             makeBad\n",
        )
        .unwrap();
        // A hidden `sorry` in a definition the target uses, and in a `«…»`-quoted target name.
        fs::write(
            root.join("J.lean"),
            "theorem good : 1 + 1 = 2 := rfl\n\
             macro \"cheat\" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 \"Lean\" \"Parser\" \"Term\" (\"sor\" ++ \"ry\")) #[Lean.Syntax.atom .none (\"sor\" ++ \"ry\")]⟩\n\
             def helper : False := cheat\n\
             theorem bad : False := helper\n",
        )
        .unwrap();
        fs::write(
            root.join("K.lean"),
            "macro \"cheat\" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 \"Lean\" \"Parser\" \"Term\" (\"sor\" ++ \"ry\")) #[Lean.Syntax.atom .none (\"sor\" ++ \"ry\")]⟩\n\
             theorem «bad» : False := cheat\n\
             theorem good : True := trivial\n",
        )
        .unwrap();
        // The same hidden `sorry`, with its warning swallowed (and the file made non-shardable).
        fs::write(
            root.join("I.lean"),
            "macro \"cheat\" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 \"Lean\" \"Parser\" \"Term\" (\"sor\" ++ \"ry\")) #[Lean.Syntax.atom .none (\"sor\" ++ \"ry\")]⟩\n\
             #guard_msgs (drop warning) in\n\
             theorem sneaky : False := cheat\n",
        )
        .unwrap();
        // `#print axioms` command-macro spoof, `admit` tactic, French-quote targets/stubs/dots, and namespace qualification.
        fs::write(
            root.join("N.lean"),
            "macro \"#print\" \"axioms\" _id:ident : command => `(command| #check True)\n\
             macro \"cheat\" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 \"Lean\" \"Parser\" \"Term\" (\"sor\" ++ \"ry\")) #[Lean.Syntax.atom .none (\"sor\" ++ \"ry\")]⟩\n\
             theorem spoofed : False := cheat\n\
             theorem via_admit : False := by admit\n",
        )
        .unwrap();
        fs::write(
            root.join("Q.lean"),
            "namespace Ns\n\
             theorem «pre.stub» : 1 + 1 = 2 := rfl\n\
             theorem «ok.thm» : 1 + 1 = 2 := «pre.stub»\n\
             theorem «bad.thm» : False := sorry\n\
             end Ns\n\
             namespace Other\n\
             theorem «bad.thm» : True := trivial\n\
             end Other\n",
        )
        .unwrap();
        // Same short name across root and sibling namespaces: prefix stubs must not collide across
        // scopes, `_root_.same` anchors to root, and bare `same` is rejected as ambiguous.
        fs::write(
            root.join("R.lean"),
            "theorem same : 1 + 1 = 2 := rfl\n\
             namespace A\n\
             theorem same : 2 + 2 = 4 := rfl\n\
             end A\n\
             namespace B\n\
             theorem same : False := sorry\n\
             end B\n",
        )
        .unwrap();
        // A `sorryAx` theorem injected under a colliding `userNameComponents` identity (`N.1` vs `N.«1»`):
        // live zygote + daemon and `--no-daemon` must reject the ambiguous stub identity.
        fs::write(
            root.join("S.lean"),
            "import Lean\n\
             namespace N\n\
             local macro_rules | `(term| sorry) => `(term| trivial)\n\
             theorem «1» : True := rfl\n\
             end N\n\
             open Lean Elab Command in\n\
             elab \"inject\" : command => liftCoreM do\n\
               addDecl <| .thmDecl { name := Name.mkNum `N 1, levelParams := [], type := mkConst ``False, value := mkApp2 (mkConst ``sorryAx [0]) (mkConst ``False) (mkConst ``Bool.false) }\n\
             inject\n\
             theorem tgt : False := by\n\
               run_tac do\n\
                 (← Lean.Elab.Tactic.getMainGoal).assign (Lean.mkConst (Lean.Name.mkNum `N 1))\n",
        )
        .unwrap();
        Self(root)
    }

    fn check(&self, file: &str, decl: &str, daemon: bool) -> Output {
        self.run(&["check", file, "--decl", decl], daemon)
    }

    fn run(&self, args: &[&str], daemon: bool) -> Output {
        let mut cmd = Command::new(env!("CARGO_BIN_EXE_turbo-lean"));
        for (key, _) in std::env::vars_os() {
            let k = key.to_string_lossy();
            if k.starts_with("TURBO_LEAN_") && k != "TURBO_LEAN_GIT" {
                cmd.env_remove(key);
            }
        }
        cmd.current_dir(&self.0)
            .args(["--json", "--cache-dir"])
            .arg(self.0.join("cache"))
            .args(args)
            .env("TURBO_LEAN_HOME", self.0.join("cache"))
            .env("TURBO_LEAN_STAGING_DIR", self.0.join("staging"))
            .env("TURBO_LEAN_TELEMETRY", "off")
            // A cold run also builds the zygote worker; keep that within the per-check timeout.
            .env("TURBO_LEAN_TIMEOUT_MS", "600000")
            .env("LEAN_NUM_THREADS", "4");
        if !daemon {
            cmd.env("TURBO_LEAN_NO_DAEMON", "1");
        }
        cmd.output().unwrap()
    }
}
impl Drop for Project {
    fn drop(&mut self) {
        stop_daemons(&self.0.join("cache"));
        stop_daemons(&self.0.join("staging"));
        let _ = fs::remove_dir_all(&self.0);
    }
}

/// Kill the local zygote daemons a test run spawned under `cache`.
fn stop_daemons(cache: &Path) {
    let mut stack = vec![cache.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in fs::read_dir(&dir).into_iter().flatten().flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if path
                .file_name()
                .is_some_and(|n| n.to_string_lossy().contains("zygote_daemon"))
            {
                let pid = fs::read(&path)
                    .ok()
                    .and_then(|b| serde_json::from_slice::<Value>(&b).ok())
                    .and_then(|v| v["pid"].as_u64());
                if let Some(pid) = pid {
                    let _ = Command::new("kill").arg(pid.to_string()).status();
                }
            }
        }
    }
}

fn status(out: &Output) -> String {
    serde_json::from_slice::<Value>(&out.stdout)
        .ok()
        .and_then(|v| v["status"].as_str().map(String::from))
        .unwrap_or_default()
}

fn assert_rejected(p: &Project, file: &str, decl: &str, daemon: bool) {
    // Twice: a rejected target must not have been cached by the first run either.
    for run in 0..2 {
        let out = p.check(file, decl, daemon);
        let st = status(&out);
        assert!(
            !out.status.success() && !st.contains("verified") && !st.contains("cache_hit"),
            "{file} --decl {decl} (daemon={daemon}, run {run}) must be rejected, got exit {:?} status {st:?}:\n{}{}",
            out.status.code(),
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
    }
}

fn lean_available() -> bool {
    Command::new("lean").arg("--version").output().is_ok()
}

#[test]
fn check_decl_rejects_sorry_target_and_keeps_prefix_stubs() {
    if !lean_available() {
        return;
    }
    for daemon in [false, true] {
        let p = Project::new(daemon);
        assert_rejected(&p, "F.lean", "bad", daemon);
        let good = p.check("G.lean", "uses_good", daemon);
        assert!(
            good.status.success()
                && matches!(
                    status(&good).as_str(),
                    "theorem_verified" | "theorem_cache_hit"
                ),
            "G.lean --decl uses_good (daemon={daemon}) must verify through the prefix stub:\n{}{}",
            String::from_utf8_lossy(&good.stdout),
            String::from_utf8_lossy(&good.stderr)
        );
        assert_rejected(&p, "G.lean", "sneaky", daemon);
        // Whole-file and directory checks reject too, even with the targets' shards attempted above;
        // the hidden `sorry` of `H.lean` first, so its whole-file check cannot seed `--decl` caches.
        assert_rejected(&p, "J.lean", "bad", daemon);
        assert_rejected(&p, "K.lean", "«bad»", daemon);
        assert_rejected(&p, "K.lean", "bad", daemon);
        assert_rejected(&p, "N.lean", "spoofed", daemon);
        assert_rejected(&p, "N.lean", "via_admit", daemon);
        for qgood in ["«ok.thm»", "Ns.«ok.thm»"] {
            let ok = p.check("Q.lean", qgood, daemon);
            assert!(
                ok.status.success()
                    && matches!(
                        status(&ok).as_str(),
                        "theorem_verified" | "theorem_cache_hit"
                    ),
                "Q.lean --decl {qgood} (daemon={daemon}) must verify through French-quote prefix stub:\n{}{}",
                String::from_utf8_lossy(&ok.stdout),
                String::from_utf8_lossy(&ok.stderr)
            );
        }
        assert_rejected(&p, "Q.lean", "«bad.thm»", daemon);
        assert_rejected(&p, "Q.lean", "Ns.«bad.thm»", daemon);
        let other_ok = p.check("Q.lean", "Other.«bad.thm»", daemon);
        assert!(
            other_ok.status.success()
                && matches!(
                    status(&other_ok).as_str(),
                    "theorem_verified" | "theorem_cache_hit"
                ),
            "Q.lean --decl Other.«bad.thm» (daemon={daemon}) must verify cleanly:\n{}{}",
            String::from_utf8_lossy(&other_ok.stdout),
            String::from_utf8_lossy(&other_ok.stderr)
        );
        for rgood in ["_root_.same", "A.same", "_root_.A.same"] {
            let ok = p.check("R.lean", rgood, daemon);
            assert!(
                ok.status.success()
                    && matches!(
                        status(&ok).as_str(),
                        "theorem_verified" | "theorem_cache_hit"
                    ),
                "R.lean --decl {rgood} (daemon={daemon}) must verify:\n{}{}",
                String::from_utf8_lossy(&ok.stdout),
                String::from_utf8_lossy(&ok.stderr)
            );
        }
        assert_rejected(&p, "R.lean", "same", daemon);
        assert_rejected(&p, "R.lean", "B.same", daemon);
        assert_rejected(&p, "R.lean", "_root_.B.same", daemon);
        assert_rejected(&p, "S.lean", "tgt", daemon);
        for target in [
            "H.lean", "I.lean", "L.lean", "M.lean", "K.lean", "J.lean", "N.lean", "Q.lean",
            "R.lean", "S.lean", "F.lean", "G.lean", ".",
        ] {
            let out = p.run(&["check", target], daemon);
            assert!(
                !out.status.success(),
                "check {target} (daemon={daemon}) must be rejected:\n{}{}",
                String::from_utf8_lossy(&out.stdout),
                String::from_utf8_lossy(&out.stderr)
            );
        }
        assert_rejected(&p, "H.lean", "sneaky", daemon);
    }
}

#[test]
fn whole_file_check_preserves_original_filename_and_dir_without_daemon() {
    if !lean_available() {
        return;
    }
    for daemon in [false, true] {
        let p = Project::new(daemon);
        let sub = p.0.join("sub");
        fs::create_dir_all(&sub).unwrap();
        fs::write(sub.join("fixture.txt"), "hello-from-sibling-fixture\n").unwrap();
        // `#eval` makes the file ineligible for sharding (`eligible_for_sharding == false`),
        // exercising the whole-file check path (including `run_audited_lean_shard_at` when
        // `TURBO_LEAN_NO_DAEMON=1` or under `module` / `IO.Process.exit` audit fallback).
        let canon_sub = sub.canonicalize().unwrap_or_else(|_| sub.clone());
        let expected_file = canon_sub.join("WithFixture.lean");
        fs::write(
            sub.join("WithFixture.lean"),
            r#"import Lean
elab "__file__" : term => do
  return Lean.mkStrLit (← Lean.getFileName)
elab "__dir__" : term => do
  let fn ← Lean.getFileName
  let d := (System.FilePath.mk fn).parent.getD (System.FilePath.mk ".")
  return Lean.mkStrLit d.toString
def embedded : String := include_str "fixture.txt"
#eval do
  let s ← IO.FS.readFile ((System.FilePath.mk __dir__) / "fixture.txt")
  if s.trimAscii.toString != "hello-from-sibling-fixture" then
    throw <| IO.userError s!"unexpected fixture: {s}"
  IO.println s!"FILE={__file__}"
theorem fixture_eq : embedded = "hello-from-sibling-fixture\n" := rfl
"#,
        )
        .unwrap();
        let out = p.run(&["check", "sub/WithFixture.lean"], daemon);
        assert!(
            out.status.success() && status(&out) == "file_verified",
            "whole-file check sub/WithFixture.lean (daemon={daemon}) must preserve __file__/__dir__:\n{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
        let v: Value = serde_json::from_slice(&out.stdout).unwrap();
        assert_eq!(
            v["mode"],
            if daemon {
                "zygote_whole_file"
            } else {
                "whole_file"
            },
            "unexpected check json: {}",
            String::from_utf8_lossy(&out.stdout)
        );
        let eval_out = v["stdout"].as_str().unwrap_or_default();
        if !daemon {
            assert!(
                eval_out.contains(&format!("FILE={}", expected_file.display())),
                "expected __file__ to point to {}, got json: {}",
                expected_file.display(),
                String::from_utf8_lossy(&out.stdout)
            );
        } else {
            let msgs_joined = v["messages"]
                .as_array()
                .map(|arr| {
                    arr.iter()
                        .filter_map(|m| m.as_str())
                        .collect::<Vec<_>>()
                        .join("\n")
                })
                .unwrap_or_default();
            let combined = format!("{eval_out}\n{msgs_joined}");
            assert!(
                combined.contains("FILE=")
                    && combined.contains("WithFixture.lean")
                    && !combined.contains("TurboAuditedShard_"),
                "expected __file__ to preserve WithFixture.lean, got json: {}",
                String::from_utf8_lossy(&out.stdout)
            );
        }

        // Also exercise `--project-dir` from a different working directory.
        let outside = std::env::temp_dir().join(format!(
            "turbo_outside_cwd_{}_{}",
            daemon,
            std::process::id()
        ));
        fs::create_dir_all(&outside).unwrap();
        let mut ext_cmd = Command::new(env!("CARGO_BIN_EXE_turbo-lean"));
        ext_cmd
            .current_dir(&outside)
            .args(["--json", "--cache-dir"])
            .arg(p.0.join("cache"))
            .args([
                "check",
                "sub/WithFixture.lean",
                "--project-dir",
                &p.0.to_string_lossy(),
            ])
            .env("TURBO_LEAN_HOME", p.0.join("cache"))
            .env("TURBO_LEAN_STAGING_DIR", p.0.join("staging"))
            .env("TURBO_LEAN_TELEMETRY", "off")
            .env("TURBO_LEAN_TIMEOUT_MS", "600000")
            .env("LEAN_NUM_THREADS", "4");
        if !daemon {
            ext_cmd.env("TURBO_LEAN_NO_DAEMON", "1");
        }
        let ext_out = ext_cmd.output().unwrap();
        let _ = fs::remove_dir_all(&outside);
        assert!(
            ext_out.status.success() && status(&ext_out) == "file_verified",
            "whole-file check with --project-dir (daemon={daemon}) failed:\n{}{}",
            String::from_utf8_lossy(&ext_out.stdout),
            String::from_utf8_lossy(&ext_out.stderr)
        );

        // Also verify whole-file soundness rejection still fires on this path when a hidden sorry is added.
        fs::write(
            sub.join("BadFixture.lean"),
            r#"import Lean
def embedded : String := include_str "fixture.txt"
macro "cheat" : term => return ⟨Lean.Syntax.node .none (Lean.Name.mkStr4 "Lean" "Parser" "Term" ("sor" ++ "ry")) #[Lean.Syntax.atom .none ("sor" ++ "ry")]⟩
#eval IO.println embedded.trimAscii
#guard_msgs (drop warning) in
theorem bad : False := cheat
"#,
        )
        .unwrap();
        let bad_out = p.run(&["check", "sub/BadFixture.lean"], daemon);
        assert!(
            !bad_out.status.success(),
            "whole-file check sub/BadFixture.lean (daemon={daemon}) must still reject hidden sorry:\n{}{}",
            String::from_utf8_lossy(&bad_out.stdout),
            String::from_utf8_lossy(&bad_out.stderr)
        );
    }
}

#[test]
fn round9_whole_file_toctou_and_lexer_cache_soundness() {
    if !lean_available() {
        return;
    }
    let p = Project::new(false);

    // 1. TOCTOU regression: if the live file on disk mutates during whole-file compilation
    //    (e.g. `#eval` or a concurrent writer overwrites `Toctou.lean` from `False` to `True`),
    //    `turbo-lean check` (with daemon=false, hitting `run_audited_lean_shard_at(..., Some(orig))`)
    //    must reject the run and NEVER poison the persistent `theorem_shard` CAS for `False`.
    let toctou_path = p.0.join("Toctou.lean");
    let false_src = r#"import Lean
elab "__file__" : term => do
  return Lean.mkStrLit (← Lean.getFileName)
#eval do
  IO.FS.writeFile (__file__) "theorem target : True := trivial\n"
theorem target : False := by trivial
"#;
    fs::write(&toctou_path, false_src).unwrap();
    let race_out = p.run(&["check", "Toctou.lean"], false);
    assert!(
        !race_out.status.success(),
        "TOCTOU self-overwrite during whole-file check must be rejected:\n{}{}",
        String::from_utf8_lossy(&race_out.stdout),
        String::from_utf8_lossy(&race_out.stderr)
    );

    // Re-write the exact original `False` file (which shares the same `theorem_shard` key for `target`
    // if `prefix_env_hash` matches, and also test pure `False` with identical prefix): neither may hit CAS!
    fs::write(&toctou_path, false_src).unwrap();
    let retry_decl = p.run(&["check", "Toctou.lean", "--decl", "target"], false);
    assert!(
        !retry_decl.status.success(),
        "CAS must not be poisoned for `target : False` after TOCTOU overwrite attempt:\n{}{}",
        String::from_utf8_lossy(&retry_decl.stdout),
        String::from_utf8_lossy(&retry_decl.stderr)
    );

    // Also test an external concurrent writer racing while `RaceExt.lean` is checked on the whole-file path.
    let race_ext = p.0.join("RaceExt.lean");
    let ext_false = "#eval IO.sleep 150\ntheorem ext_target : False := by trivial\n";
    let ext_true = "#eval IO.sleep 150\ntheorem ext_target : True := trivial\n";
    fs::write(&race_ext, ext_false).unwrap();
    let race_ext_bg = race_ext.clone();
    let writer = std::thread::spawn(move || {
        std::thread::sleep(std::time::Duration::from_millis(20));
        let _ = fs::write(&race_ext_bg, ext_true);
    });
    let _ = p.run(&["check", "RaceExt.lean"], false);
    writer.join().unwrap();
    fs::write(&race_ext, ext_false).unwrap();
    let verify_ext_false = p.run(&["check", "RaceExt.lean"], false);
    assert!(
        !verify_ext_false.status.success(),
        "concurrent overwrite to True must never allow `ext_target : False` to pass on subsequent check:\n{}{}",
        String::from_utf8_lossy(&verify_ext_false.stdout),
        String::from_utf8_lossy(&verify_ext_false.stderr)
    );

    // 2. End-to-end Lean 4 kernel check for zero-hash raw strings (`r"a  b"` vs `r"a b"`),
    //    guillemet identifiers (`«Foo.Bar».«baz»`), docstrings (`/-- ... -/`), and `f1!"..."` macros.
    let lex_file = p.0.join("LexerSound.lean");
    fs::write(
        &lex_file,
        r#"import Lean

macro "f1!" s:interpolatedStr(term) : term => `(s!$s)

theorem raw_ws : r"a  b" = "a  b" := rfl

theorem custom_interp : f1!"x {"a  b"} y" = "x a  b y" := rfl

namespace «Foo.Bar»
theorem «baz qux» : True := trivial
end «Foo.Bar»

/-- first docstring -/
theorem doc_checked : True := trivial

open Lean Elab Term in
elab "doc_contains_first" : term => do
  let some doc ← findDocString? (← getEnv) ``doc_checked
    | throwError "missing docstring"
  if (doc.splitOn "first docstring").length >= 2 then
    return mkConst ``True.intro
  else
    throwError s!"unexpected docstring: {doc}"

theorem verify_doc : True := doc_contains_first
"#,
    )
    .unwrap();
    let ok_lex = p.run(&["check", "LexerSound.lean"], false);
    assert!(
        ok_lex.status.success() && status(&ok_lex) == "file_verified",
        "LexerSound.lean must verify cleanly:\n{}{}",
        String::from_utf8_lossy(&ok_lex.stdout),
        String::from_utf8_lossy(&ok_lex.stderr)
    );

    // Mutate `r"a  b"` -> `r"a b"` (must NOT false-hit cached `raw_ws` shard!)
    fs::write(
        &lex_file,
        r#"theorem raw_ws : r"a b" = "a  b" := rfl
"#,
    )
    .unwrap();
    let bad_raw = p.run(&["check", "LexerSound.lean"], false);
    assert!(
        !bad_raw.status.success(),
        "mutated zero-hash raw string `r\"a b\" = \"a  b\"` must not hit stale CAS:\n{}{}",
        String::from_utf8_lossy(&bad_raw.stdout),
        String::from_utf8_lossy(&bad_raw.stderr)
    );

    // Mutate `f1!"x {"a  b"} y"` -> `f1!"x {"a b"} y"` (must NOT false-hit cached `custom_interp` shard!)
    fs::write(
        &lex_file,
        r#"macro "f1!" s:interpolatedStr(term) : term => `(s!$s)
theorem custom_interp : f1!"x {"a b"} y" = "x a  b y" := rfl
"#,
    )
    .unwrap();
    let bad_interp = p.run(&["check", "LexerSound.lean"], false);
    assert!(
        !bad_interp.status.success(),
        "mutated `f1!` nested string literal must not hit stale CAS:\n{}{}",
        String::from_utf8_lossy(&bad_interp.stdout),
        String::from_utf8_lossy(&bad_interp.stderr)
    );

    // Mutate docstring `/-- first docstring -/` -> `/-- second docstring -/` while `verify_doc` checks it!
    fs::write(
        &lex_file,
        r#"import Lean

/-- second docstring -/
theorem doc_checked : True := trivial

open Lean Elab Term in
elab "doc_contains_first" : term => do
  let some doc ← findDocString? (← getEnv) ``doc_checked
    | throwError "missing docstring"
  if (doc.splitOn "first docstring").length >= 2 then
    return mkConst ``True.intro
  else
    throwError s!"unexpected docstring: {doc}"

theorem verify_doc : True := doc_contains_first
"#,
    )
    .unwrap();
    let bad_doc = p.run(&["check", "LexerSound.lean"], false);
    assert!(
        !bad_doc.status.success(),
        "mutated docstring on `doc_checked` must invalidate `verify_doc`'s prefix_env_hash:\n{}{}",
        String::from_utf8_lossy(&bad_doc.stdout),
        String::from_utf8_lossy(&bad_doc.stderr)
    );
}
